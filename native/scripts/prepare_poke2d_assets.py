#!/usr/bin/env python3
"""Prepare Poké Arena 2D artwork and sprites for a compact Citro2D atlas."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


# Keep two original frames from each web animation.  Atlases are streamed per
# active combatant, preserving the source pixel art within Old 2DS VRAM.
ANIMATIONS = ("Idle", "Walk", "Attack")
MAX_FRAMES = 4
DIRECTIONS = 8
TEXT_FIRST = 32
TEXT_LAST = 126
FONT_SIZE = 40


def prepare_font(font_path: Path, output: Path) -> dict[str, int]:
    """Rasterize a regular-weight, high-resolution font for the 3DS screens."""
    font = ImageFont.truetype(str(font_path), FONT_SIZE)
    output.mkdir(parents=True, exist_ok=True)
    advances: dict[str, int] = {}
    for code in range(TEXT_FIRST, TEXT_LAST + 1):
        character = chr(code)
        advances[str(code)] = max(1, round(font.getlength(character)))
        if character == " ":
            continue
        left, top, right, bottom = font.getbbox(character, anchor="ls")
        glyph = Image.new("RGBA", (max(1, right - left), max(1, bottom - top)))
        ImageDraw.Draw(glyph).text((-left, -top), character, font=font,
                                   fill=(255, 255, 255, 255), anchor="ls")
        glyph.save(output / f"font_fill_{code:03d}.png", optimize=True)
    return advances


def write_metadata_header(path: Path, advances: dict[str, int], manifest: dict,
                          source: Path) -> None:
    roster_data = json.loads((source / "web-roster.json").read_text())
    roster = roster_data["roster"]
    forms = roster_data["forms"]
    art_dexes = list(dict.fromkeys(form["dex"] for form in forms))
    base_dexes = {mon["dex"] for mon in roster}
    form_owner: dict[int, tuple[int, dict]] = {}
    for roster_index, pokemon in enumerate(roster):
        for form_index in [pokemon["baseForm"], *pokemon["evolutionForms"],
                           *[index for index in pokemon["megaForms"] if index >= 0]]:
            form_owner[form_index] = (roster_index, pokemon)
    out = [
        "/* Generated by scripts/prepare_poke2d_assets.py. */",
        "#pragma once",
        f"#define P2D_SPECIES_COUNT {len(art_dexes)}",
        f"#define P2D_FORM_COUNT {len(forms)}",
        "#define P2D_ANIM_COUNT 3",
        "#define P2D_DIR_COUNT 8",
        f"#define P2D_MAX_FRAMES {MAX_FRAMES}",
        "#define P2D_TEXT_FIRST 32",
        "#define P2D_TEXT_COUNT 95",
        "",
    ]
    for i, pokemon in enumerate(roster):
        for animation in ANIMATIONS:
            out.append(f'#include "poke2d_sprite_indices_{group_name(i, pokemon)}_{animation.lower()}.h"')
    out.extend(['#include "poke2d_icon_indices.h"', ""])

    out.append("static const float p2dSpeciesScale[P2D_SPECIES_COUNT] = {")
    out.append("    " + ", ".join("1.000f" for _ in art_dexes) + ",")
    out.append("};")

    for name, column, ctype in (("p2dFrameHeight", 2, "unsigned short"),
                                ("p2dOriginX", 4, "unsigned short"),
                                ("p2dOriginY", 5, "unsigned short")):
        out.append(f"static const {ctype} {name}[P2D_SPECIES_COUNT][P2D_ANIM_COUNT] = {{")
        for dex in art_dexes:
            clips = [manifest[dex]["anims"][animation] for animation in ANIMATIONS]
            values = []
            for clip in clips:
                dim = clip["fh"] if column == 2 else clip["fw"]
                if column == 4: dim //= 2
                if column == 5: dim = clip["fh"]
                values.append(str(dim))
            out.append("    { " + ", ".join(values) + " },")
        out.append("};")

    out.append("static const unsigned char p2dFrameCount[P2D_SPECIES_COUNT][P2D_ANIM_COUNT] = {")
    for dex in art_dexes:
        frame_limit = MAX_FRAMES if dex in base_dexes else 1
        values = [str(min(len(manifest[dex]["anims"][animation]["durations"]), frame_limit))
                  for animation in ANIMATIONS]
        out.append("    { " + ", ".join(values) + " },")
    out.append("};")

    out.append("static const unsigned short p2dSpriteIndex[P2D_FORM_COUNT][P2D_ANIM_COUNT][P2D_DIR_COUNT][P2D_MAX_FRAMES] = {")
    for form_index, form in enumerate(forms):
        owner_index, pokemon = form_owner[form_index]
        dex = form["dex"]
        frame_limit = MAX_FRAMES if dex in base_dexes else 1
        out.append("    {")
        for anim in ANIMATIONS:
            group = f"{group_name(owner_index, pokemon)}_{anim.lower()}"
            out.append("        {")
            for direction in range(DIRECTIONS):
                indexes = [
                    f"poke2d_sprite_indices_{group}_p{dex.replace('-', '_')}_{anim.lower()}_d{direction}_f{min(frame, frame_limit - 1)}_idx"
                    for frame in range(MAX_FRAMES)
                ]
                out.append("            { " + ", ".join(indexes) + " },")
            out.append("        },")
        out.append("    },")
    out.append("};")

    out.append("static const unsigned short p2dIconIndex[ARENA2D_ROSTER_COUNT] = {")
    for i, pokemon in enumerate(roster):
        out.append(f"    poke2d_icon_indices_roster_{i:02d}_{pokemon['id']}_idx,")
    out.append("};")

    indexes = [
        "0" if code == 32 else f"poke2d_font_indices_font_fill_{code:03d}_idx"
        for code in range(TEXT_FIRST, TEXT_LAST + 1)
    ]
    out.append("static const unsigned short p2dTextIndex[P2D_TEXT_COUNT] = {")
    for i in range(0, len(indexes), 8):
        out.append("    " + ", ".join(indexes[i:i + 8]) + ",")
    out.append("};")

    values = [str(int(advances[str(code)])) for code in range(TEXT_FIRST, TEXT_LAST + 1)]
    out.append("static const unsigned char p2dTextAdvance[P2D_TEXT_COUNT] = {")
    for i in range(0, len(values), 16):
        out.append("    " + ", ".join(values[i:i + 16]) + ",")
    out.append("};")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out) + "\n", encoding="utf-8")


def c_string(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def write_web_data_header(source: Path, output: Path) -> None:
    """Turn the authorized web roster and five move slots into native tables."""
    data = json.loads((source / "web-roster.json").read_text())
    roster = data["roster"]
    forms = data["forms"]
    moves = [move for form in forms for move in form["moves"]]
    art_dexes = list(dict.fromkeys(form["dex"] for form in forms))
    art_index = {dex: i for i, dex in enumerate(art_dexes)}
    lines = [
        "/* Generated from the authorized PokeArena2D.com roster. Music excluded. */",
        "#ifndef WEB_ARENA_DATA_H",
        "#define WEB_ARENA_DATA_H",
        f"#define ARENA2D_ROSTER_COUNT {len(roster)}",
        f"#define ARENA2D_FORM_COUNT {len(forms)}",
        f"#define ARENA2D_ART_COUNT {len(art_dexes)}",
        f"#define ARENA2D_MOVE_COUNT {len(moves)}",
        "typedef struct {",
        "    const char *id, *name;",
        "    int baseForm, evolutionCount, evolutionForms[2];",
        "    float evolutionThreshold[2], evolutionHeal;",
        "    int megaForms[3], fallbackArt;",
        "} Arena2dRosterEntry;",
        "typedef struct {",
        "    const char *name, *type1, *type2, *dex;",
        "    float base[4], scale;",
        "    int moves[5], spriteArt;",
        "} Arena2dFormEntry;",
        "typedef struct {",
        "    const char *name, *type, *kind, *effect;",
        "    float power, cooldown, range, energy, velocity;",
        "} Arena2dMoveEntry;",
        "static const Arena2dRosterEntry kArena2dRoster[ARENA2D_ROSTER_COUNT] = {",
    ]
    move_index = 0
    for index, mon in enumerate(roster):
        evolution_forms = (mon["evolutionForms"] + [-1, -1])[:2]
        thresholds = (mon["evolutionThresholds"] + [0, 0])[:2]
        mega_forms = (mon["megaForms"] + [-1, -1, -1])[:3]
        lines.append(
            "    {" + ", ".join((c_string(mon["id"]), c_string(mon["name"]),
                str(mon["baseForm"]), str(len(mon["evolutionForms"])),
                "{ " + ", ".join(str(value) for value in evolution_forms) + " }",
                "{ " + ", ".join(f"{float(value):.3f}f" for value in thresholds) + " }",
                f"{float(mon['evolutionHeal']):.3f}f",
                "{ " + ", ".join(str(value) for value in mega_forms) + " }",
                str(art_index[mon["dex"]]))) + "},")
    lines.extend(["};", "static const Arena2dFormEntry kArena2dForms[ARENA2D_FORM_COUNT] = {"])
    for form in forms:
        types = form.get("types", [])
        form_move_indexes = list(range(move_index, move_index + 5))
        move_index += 5
        stats = (form["hp"], form["attack"], form["defense"], form["speed"])
        lines.append("    {" + ", ".join((c_string(form["name"]),
            c_string(types[0] if types else "NORMAL"),
            c_string(types[1] if len(types) > 1 else ""), c_string(form["dex"]),
            "{ " + ", ".join(f"{float(value):.3f}f" for value in stats) + " }",
            f"{float(form.get('scale', 1.0)):.3f}f",
            "{ " + ", ".join(str(value) for value in form_move_indexes) + " }",
            str(art_index[form["dex"]]))) + "},")
    lines.extend(["};", "static const Arena2dMoveEntry kArena2dMoves[ARENA2D_MOVE_COUNT] = {"])
    for form in forms:
        for move in form["moves"]:
            values = (c_string(move["name"]), c_string(move["type"]),
                      c_string(move["kind"]), c_string(move["effect"]),
                      f"{float(move['power']):.3f}f", f"{float(move['cooldown']):.3f}f",
                      f"{float(move['range']):.3f}f", f"{float(move['energy']):.3f}f",
                      f"{float(move['velocity']):.3f}f")
            lines.append("    {" + ", ".join(values) + "},")
    lines.extend(["};", "#endif", ""])
    output.write_text("\n".join(lines), encoding="utf-8")


def make_stage(source: Path, output: Path,
               frame: tuple[int, int, int, int] | None = None,
               target_size: tuple[int, int] = (400, 240)) -> None:
    image = Image.open(source).convert("RGB")
    if frame is not None:
        left, top, right, bottom = frame
        if left < 0 or top < 0 or right > image.width or bottom > image.height:
            raise ValueError(f"Arena frame {frame} is outside {source}: {image.size}")
        image = image.crop(frame)
    target_ratio = target_size[0] / target_size[1]
    source_ratio = image.width / image.height
    if source_ratio > target_ratio:
        crop_width = round(image.height * target_ratio)
        left = (image.width - crop_width) // 2
        image = image.crop((left, 0, left + crop_width, image.height))
    else:
        crop_height = round(image.width / target_ratio)
        top = (image.height - crop_height) // 2
        image = image.crop((0, top, image.width, top + crop_height))
    image = image.resize(target_size, Image.Resampling.LANCZOS)
    output.parent.mkdir(parents=True, exist_ok=True)
    image.save(output, optimize=True)


def prepare_logo(source: Path, output: Path) -> None:
    image = Image.open(source).convert("RGBA")
    image.thumbnail((294, 104), Image.Resampling.LANCZOS)
    output.parent.mkdir(parents=True, exist_ok=True)
    image.save(output, optimize=True)


def prepare_web_ui_icons(source: Path, output: Path) -> None:
    """Split the authorised web UI strip into its original 108px icons."""
    strip = Image.open(source).convert("RGBA")
    cell = strip.height
    if cell <= 0 or strip.width % cell:
        raise ValueError(f"Unexpected web UI strip size: {strip.size}")
    for index in range(strip.width // cell):
        icon = strip.crop((index * cell, 0, (index + 1) * cell, cell))
        icon.save(output / f"ui_icon_{index:02d}.png", optimize=True)


def group_name(index: int, pokemon: dict) -> str:
    return f"r{index:02d}_{pokemon['id']}"


def write_asset_archive_header(roster: list[dict], output: Path) -> None:
    lines = [
        "/* Generated by scripts/prepare_poke2d_assets.py. */",
        "#pragma once",
        "typedef struct { const unsigned char *start, *end; } P2dEmbeddedAtlas;",
    ]
    for index, pokemon in enumerate(roster):
        for animation in ANIMATIONS:
            group = f"{group_name(index, pokemon)}_{animation.lower()}"
            prefix = f"p2d_fighter_atlas_{group}"
            lines.extend((f"extern const unsigned char {prefix}_start[];",
                          f"extern const unsigned char {prefix}_end[];",
                          "__asm__(",
                          '    ".section .rodata\\n"',
                          '    ".balign 4\\n"',
                          f'    ".global {prefix}_start\\n"',
                          f'    "{prefix}_start:\\n"',
                          f'    ".incbin \\\"../generated/pokearena2d/{group}.t3x\\\"\\n"',
                          f'    ".global {prefix}_end\\n"',
                          f'    "{prefix}_end:\\n"',
                          '    ".text\\n"',
                          ");"))
    lines.append(f"static const P2dEmbeddedAtlas p2dFighterAtlasData[ARENA2D_ROSTER_COUNT][{len(ANIMATIONS)}] = {{")
    for index, pokemon in enumerate(roster):
        entries = []
        for animation in ANIMATIONS:
            prefix = f"p2d_fighter_atlas_{group_name(index, pokemon)}_{animation.lower()}"
            entries.append(f"{{ {prefix}_start, {prefix}_end }}")
        lines.append("    { " + ", ".join(entries) + " },")
    lines.extend(("};", ""))
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=Path("assets/pokearena2d/source"))
    parser.add_argument("--output", type=Path, default=Path("generated/pokearena2d"))
    parser.add_argument("--include", type=Path, default=Path("include/poke2d_sprite_meta.h"))
    parser.add_argument("--web-data-header", type=Path, default=Path("include/web_arena_data.h"))
    parser.add_argument("--asset-header", type=Path, default=Path("include/poke2d_asset_archive.h"))
    args = parser.parse_args()

    atlas_dir = args.output / "atlas_input"
    icon_dir = args.output / "icon_input"
    font_atlas_dir = args.output / "font_input"
    background_dir = args.output / "background_input"
    atlas_dir.mkdir(parents=True, exist_ok=True)
    font_atlas_dir.mkdir(parents=True, exist_ok=True)
    background_dir.mkdir(parents=True, exist_ok=True)
    for directory in (atlas_dir, icon_dir, font_atlas_dir, background_dir):
        if directory.exists():
            for stale in directory.rglob("*.png"):
                stale.unlink()
    make_stage(args.source / "menu-background.jpg", background_dir / "bg_menu_background.png")
    # Load the four selectable arenas from the authorized web game. The source
    # images are resampled once for the 3DS top screen to preserve detail.
    for arena in ("stadium", "neon", "crater", "ruinas"):
        make_stage(args.source / f"arena-{arena}.jpg",
                   background_dir / f"bg_arena_{arena}.png")
    make_stage(args.source / "web-title-dia.jpg", background_dir / "bg_web_title.png")
    prepare_logo(args.source / "logo.png", icon_dir / "game_logo.png")
    prepare_web_ui_icons(args.source / "ui-iconos.png", icon_dir)

    roster_data = json.loads((args.source / "web-roster.json").read_text())
    roster = roster_data["roster"]
    forms = roster_data["forms"]
    manifest = json.loads((args.source / "web-pmd-manifest.json").read_text())
    base_dexes = {mon["dex"] for mon in roster}
    for roster_index, pokemon in enumerate(roster):
        group = group_name(roster_index, pokemon)
        form_indices = [pokemon["baseForm"], *pokemon["evolutionForms"],
                        *[form for form in pokemon["megaForms"] if form >= 0]]
        dexes = list(dict.fromkeys(forms[index]["dex"] for index in form_indices))
        for dex in dexes:
            prefix = f"p{dex.replace('-', '_')}"
            frame_limit = MAX_FRAMES if dex in base_dexes else 1
            for animation in ANIMATIONS:
                group_dir = atlas_dir / f"{group}_{animation.lower()}"
                group_dir.mkdir(parents=True, exist_ok=True)
                clip = manifest[dex]["anims"].get(animation) or manifest[dex]["anims"].get("Shoot") or manifest[dex]["anims"]["Idle"]
                frame_w, frame_h = clip["fw"], clip["fh"]
                frame_count = len(clip["durations"])
                source_path = args.source / "pmd" / dex / f"{animation}.png"
                if not source_path.exists():
                    source_path = args.source / "pmd" / dex / f"{clip['file'].split('/')[-1]}"
                source = Image.open(source_path).convert("RGBA")
                expected = (frame_w * frame_count, frame_h * DIRECTIONS)
                if source.size != expected:
                    raise ValueError(f"Unexpected {dex}/{animation} sheet: {source.size}, expected {expected}")
                keep = min(frame_count, frame_limit)
                for direction in range(DIRECTIONS):
                    for frame in range(frame_limit):
                        source_frame = min(frame, keep - 1)
                        cell = source.crop((source_frame * frame_w, direction * frame_h,
                                            (source_frame + 1) * frame_w, (direction + 1) * frame_h))
                        cell.save(group_dir / f"{prefix}_{animation.lower()}_d{direction}_f{frame}.png",
                                  optimize=True)
            if dex == pokemon["dex"]:
                idle = manifest[dex]["anims"]["Idle"]
                idle_path = args.source / "pmd" / dex / f"Idle.png"
                if not idle_path.exists():
                    idle_path = args.source / "pmd" / dex / idle["file"].split("/")[-1]
                sheet = Image.open(idle_path).convert("RGBA")
                icon = sheet.crop((0, 0, idle["fw"], idle["fh"]))
                icon.save(icon_dir / f"roster_{roster_index:02d}_{pokemon['id']}.png",
                          optimize=True)

    advances = prepare_font(args.source / "font" / "OpenSans-Regular.ttf", font_atlas_dir)
    write_metadata_header(args.include, advances, manifest, args.source)
    write_web_data_header(args.source, args.web_data_header)
    write_asset_archive_header(roster, args.asset_header)
    print(f"Prepared {len(list(atlas_dir.rglob('*.png')))} sprites, "
          f"{len(list(font_atlas_dir.glob('*.png')))} font glyphs, and "
          f"{len(list(background_dir.glob('*.png')))} backgrounds")


if __name__ == "__main__":
    main()
