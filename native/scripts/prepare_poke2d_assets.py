#!/usr/bin/env python3
"""Prepare the captured Poke2D Arena sheets for a small Citro2D atlas."""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image


# These frame rectangles and pivots are from the public movementClips.generated
# data served by poke2darena.com/play-online. Each animation sheet has eight
# direction rows and consecutive frames across each row.
POKEMON = [
    ("p25", "Pikachu", "0025", 0.77, [
        ("Idle", 40, 56, 6, 20, 32),
        ("Walk", 32, 40, 4, 16, 24),
        ("Shoot", 40, 56, 11, 20, 31),
    ]),
    ("p208", "Steelix", "0208", 0.48, [
        ("Idle", 64, 112, 4, 32, 60),
        ("Walk", 72, 112, 4, 36, 60),
        ("Shoot", 96, 120, 12, 48, 62),
    ]),
    ("p212", "Scizor", "0212", 0.78, [
        ("Idle", 32, 64, 6, 16, 36),
        ("Walk", 40, 48, 4, 20, 28),
        ("Shoot", 48, 56, 12, 24, 31),
    ]),
    ("p130", "Gyarados", "0130", 0.43, [
        ("Idle", 72, 128, 4, 36, 68),
        ("Walk", 88, 128, 4, 44, 68),
        ("Shoot", 104, 128, 12, 52, 66),
    ]),
    ("p6", "Charizard", "0006", 0.90, [
        ("Idle", 40, 48, 4, 20, 28),
        ("Walk", 40, 48, 4, 20, 28),
        ("Shoot", 56, 56, 11, 28, 31),
    ]),
    ("p9", "Blastoise", "0009", 0.90, [
        ("Idle", 40, 40, 8, 20, 24),
        ("Walk", 32, 40, 4, 16, 24),
        ("Shoot", 48, 56, 6, 24, 32),
    ]),
]

ANIMATIONS = ("Idle", "Walk", "Shoot")
MAX_FRAMES = 4
DIRECTIONS = 8


def write_metadata_header(path: Path) -> None:
    out = [
        "/* Generated by scripts/prepare_poke2d_assets.py. */",
        "#pragma once",
        "#define P2D_SPECIES_COUNT 6",
        "#define P2D_ANIM_COUNT 3",
        "#define P2D_DIR_COUNT 8",
        "#define P2D_MAX_FRAMES 4",
        "",
    ]

    out.append("static const float p2dSpeciesScale[P2D_SPECIES_COUNT] = {")
    out.append("    " + ", ".join(f"{species[3]:.3f}f" for species in POKEMON) + ",")
    out.append("};")

    for name, column, ctype in (("p2dFrameHeight", 2, "unsigned short"),
                                ("p2dOriginX", 4, "unsigned short"),
                                ("p2dOriginY", 5, "unsigned short")):
        out.append(f"static const {ctype} {name}[P2D_SPECIES_COUNT][P2D_ANIM_COUNT] = {{")
        for species in POKEMON:
            values = [str(species[4][i][column] // 2) for i in range(len(ANIMATIONS))]
            out.append("    { " + ", ".join(values) + " },")
        out.append("};")

    out.append("static const unsigned char p2dFrameCount[P2D_SPECIES_COUNT][P2D_ANIM_COUNT] = {")
    for species in POKEMON:
        values = [str(min(species[4][i][3], MAX_FRAMES)) for i in range(len(ANIMATIONS))]
        out.append("    { " + ", ".join(values) + " },")
    out.append("};")

    out.append("static const unsigned short p2dSpriteIndex[P2D_SPECIES_COUNT][P2D_ANIM_COUNT][P2D_DIR_COUNT][P2D_MAX_FRAMES] = {")
    for prefix, _display, _dex, _scale, _clips in POKEMON:
        out.append("    {")
        for anim in ANIMATIONS:
            out.append("        {")
            for direction in range(DIRECTIONS):
                indexes = [
                    f"poke2d_sprite_indices_{prefix}_{anim.lower()}_d{direction}_f{frame}_idx"
                    for frame in range(MAX_FRAMES)
                ]
                out.append("            { " + ", ".join(indexes) + " },")
            out.append("        },")
        out.append("    },")
    out.append("};")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(out) + "\n", encoding="utf-8")


def make_stage(source: Path, output: Path) -> None:
    image = Image.open(source).convert("RGB")
    target_ratio = 400 / 240
    source_ratio = image.width / image.height
    if source_ratio > target_ratio:
        crop_width = round(image.height * target_ratio)
        left = (image.width - crop_width) // 2
        image = image.crop((left, 0, left + crop_width, image.height))
    else:
        crop_height = round(image.width / target_ratio)
        top = (image.height - crop_height) // 2
        image = image.crop((0, top, image.width, top + crop_height))
    image = image.resize((400, 240), Image.Resampling.LANCZOS)
    output.parent.mkdir(parents=True, exist_ok=True)
    image.save(output, optimize=True)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=Path("assets/poke2d/source"))
    parser.add_argument("--output", type=Path, default=Path("generated/poke2d"))
    parser.add_argument("--include", type=Path, default=Path("include/poke2d_sprite_meta.h"))
    args = parser.parse_args()

    atlas_dir = args.output / "atlas_input"
    atlas_dir.mkdir(parents=True, exist_ok=True)
    make_stage(args.source / "volcanic_arena.png", atlas_dir / "arena_volcanic.png")
    make_stage(args.source / "grass_arena.png", atlas_dir / "arena_grass.png")

    for prefix, _display, dex, scale, clips in POKEMON:
        for animation_index, (animation, frame_w, frame_h, frame_count, _ox, _oy) in enumerate(clips):
            source = Image.open(args.source / dex / f"{animation}.png").convert("RGBA")
            expected = (frame_w * frame_count, frame_h * DIRECTIONS)
            if source.size != expected:
                raise ValueError(f"Unexpected {dex}/{animation} sheet: {source.size}, expected {expected}")
            keep = min(frame_count, MAX_FRAMES)
            for direction in range(DIRECTIONS):
                for frame in range(keep):
                    cell = source.crop((frame * frame_w, direction * frame_h,
                                        (frame + 1) * frame_w, (direction + 1) * frame_h))
                    # Half-resolution nearest-neighbour frames preserve the original
                    # pixel-art edges and keep the atlas small enough for Old 2DS.
                    resized = (max(1, cell.width // 2), max(1, cell.height // 2))
                    cell = cell.resize(resized, Image.Resampling.NEAREST)
                    cell.save(atlas_dir / f"{prefix}_{animation.lower()}_d{direction}_f{frame}.png",
                              optimize=True)

    write_metadata_header(args.include)
    print(f"Prepared {len(list(atlas_dir.glob('*.png')))} atlas images in {atlas_dir}")


if __name__ == "__main__":
    main()
