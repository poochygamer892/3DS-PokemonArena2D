#!/usr/bin/env python3
"""Pack PokeAPI's Pokémon PNG sprites into Citro2D-friendly color runs."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
IDS = (25, 1, 7, 130, 6, 133)
SIZES = (48, 16)


def rgba32(c):
    r, g, b, a = c
    return (r << 24) | (g << 16) | (b << 8) | a


def make_sprite(facing, species, size):
    image = Image.open(ROOT / "assets" / "pokemon" / facing / f"{species}.png").convert("RGBA")
    image = image.crop(image.getchannel("A").getbbox())
    factor = size / max(image.size)
    fitted = (max(1, round(image.width * factor)), max(1, round(image.height * factor)))
    image = image.resize(fitted, Image.Resampling.NEAREST)
    canvas = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    canvas.alpha_composite(image, ((size - image.width) // 2, (size - image.height) // 2))

    runs = []
    for y in range(size):
        x = 0
        while x < size:
            color = canvas.getpixel((x, y))
            if color[3] == 0:
                x += 1
                continue
            x1 = x + 1
            while x1 < size and canvas.getpixel((x1, y)) == color:
                x1 += 1
            runs.append((x, y, x1 - x, rgba32(color)))
            x = x1
    return runs


sprites = {
    (size, facing, species): make_sprite(facing, species, size)
    for size in SIZES
    for facing in ("front", "back")
    for species in IDS
}

out = ["/* Generated by scripts/build_sprite_header.py; do not edit by hand. */",
       "#pragma once", "#include <stdint.h>",
       "typedef struct { uint8_t x, y, w; uint32_t rgba; } PokemonSpriteRun;"]
for size in SIZES:
    for facing in ("front", "back"):
        for species in IDS:
            runs = sprites[(size, facing, species)]
            name = f"kSprite{size}_{facing}_{species}"
            out.append(f"static const PokemonSpriteRun {name}[] = {{")
            for x, y, width, color in runs:
                out.append(f"    {{{x}, {y}, {width}, 0x{color:08X}u}},")
            out.append("};")

for size in SIZES:
    out.append(f"static const PokemonSpriteRun *const kPokemonSprites{size}[2][6] = {{")
    for facing in ("front", "back"):
        out.append("    {" + ", ".join(f"kSprite{size}_{facing}_{species}" for species in IDS) + "},")
    out.append("};")
    out.append(f"static const uint16_t kPokemonSpriteRunCount{size}[2][6] = {{")
    for facing in ("front", "back"):
        out.append("    {" + ", ".join(str(len(sprites[(size, facing, species)])) for species in IDS) + "},")
    out.append("};")

(ROOT / "source" / "pokemon_sprites.h").write_text("\n".join(out) + "\n")
print("Generated run counts:", {size: sum(len(runs) for (s, _, _), runs in sprites.items() if s == size) for size in SIZES})
